// Generate scoped theme colors for existing admin managers without restyling public pages.
const fs=require('fs'),postcss=require('postcss');
function rgb(s){if(s.startsWith('#')){let h=s.slice(1);if(h.length===3||h.length===4)h=h.split('').map(c=>c+c).join('');return [0,2,4].map(i=>parseInt(h.slice(i,i+2),16));}return s.match(/[\d.]+/g).slice(0,3).map(Number);}
function replacement(value,prop){
 const [r,g,b]=rgb(value),max=Math.max(r,g,b),min=Math.min(r,g,b),delta=max-min;
 const lum=(r*.2126+g*.7152+b*.0722)/255;
 let hue=0;if(delta){hue=max===r?((g-b)/delta)%6:max===g?(b-r)/delta+2:(r-g)/delta+4;hue=(hue*60+360)%360;}
 let tone=delta>70&&r>g*1.45&&r>b*1.1?'accent':delta>60&&b>r*1.3&&b>g*1.05?'info':delta>45&&g>r*1.25&&g>b*1.05?'success':delta>80&&r>100&&g>60&&b<r*.65?'warning':null;
 const rgba=value.match(/^rgba\([^,]+,[^,]+,[^,]+,\s*([\d.]+)\)/i);const alpha=rgba?Number(rgba[1]):1;
 if(/background/.test(prop)&&alpha<.5)return `var(--adm-${tone?tone+'-soft':'soft'})`;
 if(/border|outline|shadow/.test(prop))return 'var(--adm-line)';
 if(/background/.test(prop))return lum>.75?`var(--adm-${tone? tone+'-soft':'surface'})`:lum<.1?'var(--adm-strong)':`var(--adm-${tone?tone+'-solid':'soft'})`;
 if(/color|fill|stroke|^--/.test(prop))return lum>.96?'var(--adm-on-solid)':`var(--adm-${tone || (lum<.35?'text':'muted')})`;
 return value;
}
const sources=['src/styles/workspace.css','src/styles/admin-refactor.css','src/styles/memberships.css','src/styles/speaking-editor.css','src/components/ai-lab.css'];
const out=postcss.root();
for(const file of sources){const input=postcss.parse(fs.readFileSync(file,'utf8'));input.walkRules(rule=>{
 if(rule.parent.type==='atrule'&&/keyframes/.test(rule.parent.name))return;
 const decls=[];rule.walkDecls(d=>{if(/color|background|border|outline|fill|stroke|^--/.test(d.prop)&&/#(?:[a-f0-9]{3,8})\b|rgba?\(/i.test(d.value)){
  const value=d.value.replace(/#[a-f0-9]{8}\b|#[a-f0-9]{6}\b|#[a-f0-9]{4}\b|#[a-f0-9]{3}\b|rgba?\([^)]*\)/gi,v=>replacement(v,d.prop));
  if(value!==d.value)decls.push(postcss.decl({prop:d.prop,value,important:d.important}));
 }});
 if(!decls.length)return;
 const next=postcss.rule({selector:rule.selectors.filter(s=>!/^html|^body|:root/.test(s)).map(s=>'.admin-app '+s).join(',')});if(!next.selector)return;decls.forEach(d=>next.append(d));
 if(rule.parent.type==='atrule'&&rule.parent.name==='media'){const media=postcss.atRule({name:'media',params:rule.parent.params});media.append(next);out.append(media);}else out.append(next);
 });}
fs.writeFileSync('src/styles/admin-theme-bridge.css','/* Generated by scripts/design/admin-theme-bridge.cjs. Scope is admin only. */\n'+out.toString());
// This CSS module is admin-only. Variable fallbacks preserve its standalone rendering.
const mock='src/components/mocks.module.css';const moduleCss=postcss.parse(fs.readFileSync(mock,'utf8'));
moduleCss.walkDecls(d=>{if(d.value.includes('var(--adm-'))return;d.value=d.value.replace(/#[a-f0-9]{8}\b|#[a-f0-9]{6}\b|#[a-f0-9]{4}\b|#[a-f0-9]{3}\b/gi,v=>{const token=replacement(v,d.prop);return token.startsWith('var(')?token.slice(0,-1)+','+v+')':v;});});
fs.writeFileSync(mock,moduleCss.toString());
